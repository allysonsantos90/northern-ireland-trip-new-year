function updateShare() {
  document.getElementById("whatsappShare").href = "https://wa.me/?text=" + encodeURIComponent(summary());
}

function setLanguage(next) {
  if (!translations[next]) return;
  language = next;
  const dict = translations[next];
  document.documentElement.lang = next === "pt" ? "pt-BR" : "en";
  document.title = next === "pt"
    ? "Northern Ireland Escape | Réveillon 2026/27"
    : "Northern Ireland Escape | New Year 2026/27";

  document.querySelectorAll("[data-i18n]").forEach(element => {
    const key = element.dataset.i18n;
    if (dict[key] !== undefined) element.innerHTML = dict[key];
  });

  document.querySelectorAll(".lang-btn").forEach(button => {
    const active = button.dataset.lang === next;
    button.classList.toggle("active", active);
    button.setAttribute("aria-pressed", String(active));
  });

  try { localStorage.setItem("ni-escape-language", next); } catch (error) {}
  updateShare();
  status.textContent = "";
}

document.querySelector(".language-switch").addEventListener("click", event => {
  const button = event.target.closest("[data-lang]");
  if (button) setLanguage(button.dataset.lang);
});

